    #[test]
    fn test_lockfile_diff() {
        let mut old = LockFile::new();
        old.add_or_update(LockedPackage::new_registry("foo", "1.0.0", "https://reg", Some("hash1".to_string()), vec![]));
        old.add_or_update(LockedPackage::new_registry("bar", "2.0.0", "https://reg", Some("hash2".to_string()), vec![]));

        let mut new_lock = LockFile::new();
        new_lock.add_or_update(LockedPackage::new_registry("foo", "1.1.0", "https://reg", Some("hash1_bumped".to_string()), vec![])); // updated
        new_lock.add_or_update(LockedPackage::new_registry("baz", "0.5.0", "https://reg", Some("hash3".to_string()), vec![])); // added
        // bar removed

        let diff = old.diff(&new_lock);
        assert_eq!(diff.added.len(), 1);
        assert_eq!(diff.added[0].name, "baz");

        assert_eq!(diff.removed.len(), 1);
        assert_eq!(diff.removed[0].name, "bar");

        assert_eq!(diff.updated.len(), 1);
        assert_eq!(diff.updated[0].0.name, "foo");
        assert_eq!(diff.updated[0].0.version, "1.0.0");
        assert_eq!(diff.updated[0].1.version, "1.1.0");
    }

    #[test]
    fn test_is_up_to_date_validation() {
        let manifest_src = r#"
name = "my_app"
version = "0.1.0"

[dependencies]
foo = "^1.0.0"
bar = "~2.1.0"
"#;
        let config = ProjectConfig::parse(manifest_src).unwrap();

        let mut lock = LockFile::new();
        lock.add_or_update(LockedPackage::new_registry("foo", "1.2.0", "https://reg", None, vec![]));
        lock.add_or_update(LockedPackage::new_registry("bar", "2.1.5", "https://reg", None, vec![]));

        // Exactly satisfies
        assert!(lock.is_up_to_date(&config).unwrap());

        // Incompatible version for foo
        let mut bad_ver_lock = LockFile::new();
        bad_ver_lock.add_or_update(LockedPackage::new_registry("foo", "2.0.0", "https://reg", None, vec![]));
        bad_ver_lock.add_or_update(LockedPackage::new_registry("bar", "2.1.5", "https://reg", None, vec![]));
        assert!(!bad_ver_lock.is_up_to_date(&config).unwrap());

        // Missing dependency bar
        let mut missing_lock = LockFile::new();
        missing_lock.add_or_update(LockedPackage::new_registry("foo", "1.2.0", "https://reg", None, vec![]));
        assert!(!missing_lock.is_up_to_date(&config).unwrap());

        // Extra obsolete dependency in lockfile
        let mut extra_lock = lock.clone();
        extra_lock.add_or_update(LockedPackage::new_registry("obsolete", "0.1.0", "https://reg", None, vec![]));
        assert!(!extra_lock.is_up_to_date(&config).unwrap());
    }

    #[test]
    fn test_verify_checksums_pass_and_tamper_detection() {
        let temp = tempfile::tempdir().unwrap();
        let libs_dir = temp.path().join("libs");
        let pkg_dir = libs_dir.join("test_pkg");
        fs::create_dir_all(&pkg_dir).unwrap();
        fs::write(pkg_dir.join("lib.roze"), "func hello() {}").unwrap();

        let correct_hash = sha256_dir(&pkg_dir).unwrap();

        let mut lock = LockFile::new();
        lock.add_or_update(LockedPackage::new_registry(
            "test_pkg",
            "1.0.0",
            "https://reg",
            Some(correct_hash.clone()),
            vec![],
        ));

        // 1. Should be Valid
        let report = lock.verify_checksums(&libs_dir).unwrap();
        assert_eq!(report.len(), 1);
        assert_eq!(report[0].status, ChecksumStatus::Valid);
        assert!(report[0].is_valid());

        // 2. Tamper with file
        fs::write(pkg_dir.join("lib.roze"), "func hello() { /* tampered malicious payload */ }").unwrap();

        let tampered_report = lock.verify_checksums(&libs_dir).unwrap();
        assert_eq!(tampered_report.len(), 1);
        assert!(!tampered_report[0].is_valid());
        match &tampered_report[0].status {
            ChecksumStatus::Mismatch { expected, actual } => {
                assert_eq!(expected, &correct_hash);
                assert_ne!(actual, &correct_hash);
            }
            other => panic!("Expected Mismatch, got {:?}", other),
        }

        // 3. Delete directory -> Missing
        fs::remove_dir_all(&pkg_dir).unwrap();
        let missing_report = lock.verify_checksums(&libs_dir).unwrap();
        assert_eq!(missing_report.len(), 1);
        assert_eq!(missing_report[0].status, ChecksumStatus::Missing);
    }
