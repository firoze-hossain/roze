// tools/roze-pkg/src/lockfile.rs
//
// Deterministic lockfile (roze.lock) generator and parser.
// Ensures reproducible builds across environments by recording exact versions,
// package sources, dependencies, and content hashes.

use std::fs;
use std::path::Path;
use anyhow::{anyhow, Result};
use serde::{Deserialize, Serialize};

pub const LOCKFILE_NAME: &str = "roze.lock";
pub const LOCKFILE_HEADER: &str = "# This file is automatically generated by roze-pkg.\n# It is not intended for manual editing.\n\n";

#[derive(Debug, Serialize, Deserialize, Clone, PartialEq, Eq)]
pub struct LockFile {
    pub version: u32,
    #[serde(rename = "package", default)]
    pub packages: Vec<LockedPackage>,
}

#[derive(Debug, Serialize, Deserialize, Clone, PartialEq, Eq)]
pub struct LockedPackage {
    pub name: String,
    pub version: String,
    pub source: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub checksum: Option<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub dependencies: Vec<String>,
}

impl Default for LockFile {
    fn default() -> Self {
        Self::new()
    }
}

impl LockFile {
    pub fn new() -> Self {
        Self {
            version: 1,
            packages: Vec::new(),
        }
    }

    pub fn load(path: &Path) -> Result<Self> {
        if !path.exists() {
            return Err(anyhow!("Lockfile not found at {}", path.display()));
        }
        let content = fs::read_to_string(path)?;
        let lockfile: LockFile = toml::from_str(&content)?;
        Ok(lockfile)
    }

    pub fn save(&mut self, path: &Path) -> Result<()> {
        self.sort();
        let rendered = self.render()?;
        fs::write(path, rendered)?;
        Ok(())
    }

    pub fn find_package(&self, name: &str) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.name == name)
    }

    pub fn find_package_mut(&mut self, name: &str) -> Option<&mut LockedPackage> {
        self.packages.iter_mut().find(|p| p.name == name)
    }

    pub fn add_or_update(&mut self, pkg: LockedPackage) {
        if let Some(existing) = self.find_package_mut(&pkg.name) {
            *existing = pkg;
        } else {
            self.packages.push(pkg);
        }
    }

    pub fn remove_package(&mut self, name: &str) -> bool {
        let original_len = self.packages.len();
        self.packages.retain(|p| p.name != name);
        self.packages.len() < original_len
    }

    pub fn sort(&mut self) {
        self.packages.sort_by(|a, b| a.name.cmp(&b.name));
        for pkg in &mut self.packages {
            pkg.dependencies.sort();
        }
    }

    pub fn render(&self) -> Result<String> {
        let mut rendered = String::from(LOCKFILE_HEADER);
        let toml_str = toml::to_string_pretty(self)?;
        rendered.push_str(&toml_str);
        Ok(rendered)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_lockfile_roundtrip() {
        let mut lock = LockFile::new();
        lock.add_or_update(LockedPackage {
            name: "std::web".to_string(),
            version: "1.0.0".to_string(),
            source: "registry+https://registry.roze.dev".to_string(),
            checksum: Some("e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855".to_string()),
            dependencies: vec!["std::json 0.2.0".to_string()],
        });

        lock.add_or_update(LockedPackage {
            name: "std::json".to_string(),
            version: "0.2.0".to_string(),
            source: "registry+https://registry.roze.dev".to_string(),
            checksum: Some("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad".to_string()),
            dependencies: Vec::new(),
        });

        let temp = tempfile::tempdir().unwrap();
        let path = temp.path().join("roze.lock");
        lock.save(&path).unwrap();

        let loaded = LockFile::load(&path).unwrap();
        assert_eq!(loaded.version, 1);
        assert_eq!(loaded.packages.len(), 2);

        let web = loaded.find_package("std::web").unwrap();
        assert_eq!(web.version, "1.0.0");
        assert_eq!(web.dependencies, vec!["std::json 0.2.0"]);
    }
}
